export function LanguageProvider({ children }) {
  const [lang, setLang] = useState('en');

  // Load language preference from local storage
  useEffect(() => {
    const savedLang = localStorage.getItem('financecalc_lang');
    if (savedLang === 'bn' || savedLang === 'en') {
      setLang(savedLang);
    }
  }, []);

  const toggleLang = () => {
    const newLang = lang === 'en' ? 'bn' : 'en';
    setLang(newLang);
    localStorage.setItem('financecalc_lang', newLang);
  };

  const t = (path) => {
    const keys = path.split('.');
    let result = translations[lang];
    for (const key of keys) {
      if (result && result[key] !== undefined) {
        result = result[key];
      } else {
        return path; // Fallback to path key itself
      }
    }
    return result;
  };

  const fmt = (n) => {
    if (lang === 'bn') {
      return `৳${(n || 0).toLocaleString('bn-BD')}`;
    }
    return `৳${(n || 0).toLocaleString('en-US')}`;
  };

  const fmtDate = (d) => {
    if (!d) return '—';
    const dateObj = new Date(d);
    if (lang === 'bn') {
      return dateObj.toLocaleDateString('bn-BD', { month: 'long', day: 'numeric', year: 'numeric' });
    }
    return dateObj.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' });
  };

  return (
    <LanguageContext.Provider value={{ lang, toggleLang, t, fmt, fmtDate }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
